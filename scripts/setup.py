#!/usr/bin/python3
"""Install only user-owned config; never install packages or copy credentials."""
import argparse
from datetime import datetime
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys

PROJECT = Path(__file__).resolve().parents[1]
BEGIN = '-- BEGIN migleve.omp-voice (managed)'
END = '-- END migleve.omp-voice (managed)'


def managed(text, body):
    if text.count(BEGIN) != text.count(END) or text.count(BEGIN) > 1:
        raise ValueError('Malformed OMP Voice managed block; inspect hyprland.lua first.')
    if BEGIN in text:
        start, finish = text.index(BEGIN), text.index(END) + len(END)
        if finish < start:
            raise ValueError('Reversed managed block markers.')
        text = text[:start] + text[finish:].lstrip('\n')
    if body is None:
        return text
    return text.rstrip('\n') + '\n\n' + BEGIN + '\n' + body + '\n' + END + '\n'


def lua_string(value):
    # JSON string escapes are Lua-compatible for these path/command strings.
    return json.dumps(str(value), ensure_ascii=False)


def check_shortcut(shortcut, bindings):
    parts = [part.strip().upper() for part in shortcut.split('+')]
    modifier_bits = {'SHIFT': 1, 'CTRL': 4, 'CONTROL': 4, 'ALT': 8, 'SUPER': 64}
    if not parts[-1] or any(part not in modifier_bits for part in parts[:-1]):
        raise ValueError('Unsupported shortcut. Example: SUPER + ALT + V.')
    mask = 0
    for modifier in parts[:-1]:
        mask |= modifier_bits[modifier]
    for binding in bindings:
        if (str(binding.get('key', '')).upper() == parts[-1]
                and binding.get('modmask') == mask and not binding.get('submap')
                and binding.get('description') != 'OMP Voice'):
            raise ValueError('Shortcut already used by ' + binding.get('description', 'another binding')
                             + '. Choose a different --shortcut; no bindings were replaced.')


def write_backed_up(path, text, data_home):
    if path.exists() and path.read_text() == text:
        return
    if path.exists():
        backup = Path(data_home) / 'omp-voice/backups'
        backup.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, backup / (path.name + '.' + datetime.now().strftime('%Y%m%d-%H%M%S-%f')))
    path.write_text(text)


def install(config_home, data_home, bin_home, *, shortcut='SUPER + ALT + V', uninstall=False):
    config_home, data_home, bin_home = map(Path, (config_home, data_home, bin_home))
    main = config_home / 'hypr/hyprland.lua'
    if not main.is_file():
        raise ValueError('Requires Omarchy with ~/.config/hypr/hyprland.lua (Lua Hyprland).')
    if not re.fullmatch(r'[A-Za-z0-9_ +]+', shortcut):
        raise ValueError('Invalid shortcut; use e.g. SUPER + ALT + V.')
    module = config_home / 'hypr/omp-voice-plugin.lua'
    launcher = bin_home / 'omp-voice'
    previous = main.read_text()
    body = None if uninstall else 'dofile(' + lua_string(module) + ')'
    updated = managed(previous, body)
    if not uninstall:
        module.parent.mkdir(parents=True, exist_ok=True)
        launcher.parent.mkdir(parents=True, exist_ok=True)
        herdr = config_home / 'herdr/omp-voice.toml'
        herdr.parent.mkdir(parents=True, exist_ok=True)
        if not herdr.exists():
            shutil.copyfile(PROJECT / 'templates/herdr.toml', herdr)
        lua = (PROJECT / 'templates/outside-click.lua').read_text()
        # The template returns a testing API: register the window and bind before it.
        rule = '''o.window("^org\\\\.omarchy\\\\.omp-voice$", {
  float = true, center = true,
  size = { "monitor_w * 0.60", "monitor_h * 0.48" },
  rounding = 16, border_size = 2, opacity = "1 1",
})
'''
        command = shlex.quote(str(launcher)) + ' --toggle'
        rule += 'o.bind(' + lua_string(shortcut) + ', "OMP Voice", ' + lua_string(command) + ')\n'
        write_backed_up(module, '-- Generated by OMP Voice setup; rerun setup to change the shortcut.\n' + rule + lua, data_home)
        write_backed_up(launcher, '#!/usr/bin/python3\nimport os, sys\nos.execv(sys.executable, [sys.executable, '
                        + repr(str(PROJECT / 'scripts/voice.py')) + ', *sys.argv[1:]])\n', data_home)
        launcher.chmod(0o755)
    if updated != previous:
        backups = data_home / 'omp-voice/backups'
        backups.mkdir(parents=True, exist_ok=True)
        shutil.copy2(main, backups / ('hyprland.' + datetime.now().strftime('%Y%m%d-%H%M%S-%f') + '.lua'))
        main.write_text(updated)
    # Uninstall removes the managed block only; keep configs and conversations recoverable.
    return main


def checked_install(config_home, data_home, bin_home, **options):
    config_home, bin_home = Path(config_home), Path(bin_home)
    paths = [config_home / 'hypr/hyprland.lua', config_home / 'hypr/omp-voice-plugin.lua',
             config_home / 'herdr/omp-voice.toml', bin_home / 'omp-voice']
    snapshots = {path: (path.read_bytes(), path.stat().st_mode) if path.exists() else None for path in paths}
    try:
        install(config_home, data_home, bin_home, **options)
        subprocess.run(['hyprctl', 'reload'], check=True)
        result = subprocess.run(['hyprctl', 'configerrors'], check=True, capture_output=True, text=True)
        if result.stdout.strip():
            raise ValueError('Hyprland configuration errors:\n' + result.stdout)
    except (OSError, ValueError, subprocess.SubprocessError):
        for path, snapshot in snapshots.items():
            if snapshot is None:
                if path.exists():
                    path.unlink()
            else:
                path.write_bytes(snapshot[0])
                path.chmod(snapshot[1])
        # Restore the compositor too; don't mask the original diagnostic if IPC is lost.
        subprocess.run(['hyprctl', 'reload'], check=False, capture_output=True)
        subprocess.run(['hyprctl', 'configerrors'], check=False, capture_output=True)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--shortcut', default='SUPER + ALT + V')
    parser.add_argument('--uninstall', action='store_true')
    args = parser.parse_args()
    home = Path.home()
    config = Path(os.environ.get('XDG_CONFIG_HOME', home / '.config'))
    data = Path(os.environ.get('XDG_STATE_HOME', home / '.local/state'))
    if not args.uninstall:
        missing = [name for name in ('herdr', 'omp', 'hyprctl', 'omarchy-launch-tui') if not shutil.which(name)]
        if missing:
            raise ValueError('Missing dependencies on PATH: ' + ', '.join(missing) + '. See README.md.')
        bindings = subprocess.run(['hyprctl', 'binds', '-j'], check=True, capture_output=True, text=True)
        check_shortcut(args.shortcut, json.loads(bindings.stdout))
    checked_install(config, data, home / '.local/bin', shortcut=args.shortcut, uninstall=args.uninstall)
    print('OMP Voice shortcut removed; conversations retained.' if args.uninstall
          else 'OMP Voice installed. Press ' + args.shortcut + '. Log in to OMP before using voice.')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print('OMP Voice setup: ' + str(error), file=sys.stderr)
        sys.exit(1)
